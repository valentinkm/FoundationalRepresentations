"""
src/evaluation/predict_self_consistency.py

The "Self-Consistency" Judge.
Evaluates how well a model's semantic representations predict its OWN generated psycholinguistic norms.

Method:
- Ridge Regression (L2 Regularization) with Cross-Validation
- Metric: R^2 (Variance Explained)
- Matching: Embeddings for Model X are used to predict Norms generated by Model X
"""

import argparse
import pickle
import pandas as pd
import numpy as np
from pathlib import Path
from tqdm import tqdm
from sklearn.linear_model import RidgeCV
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import make_pipeline
from sklearn.model_selection import cross_val_score, KFold
from joblib import Parallel, delayed

# --- CONFIG ---
DEFAULT_ALPHAS = [1e-3, 1e-2, 1e-1, 1, 10, 100, 1000]
CV_FOLDS = 5
MIN_SAMPLES = 50  # Minimum overlapping words to attempt regression

def load_embeddings(pkl_path: Path):
    """Load the dictionary of matrices and mappings."""
    print(f"[Loader] Loading embeddings from {pkl_path}...")
    with open(pkl_path, 'rb') as f:
        data = pickle.load(f)
    return data['embeddings'], data['mappings']

def load_model_norms(norms_dir: Path, human_norms_path: Path = None, allowed_models: list = None) -> dict:
    """
    Load all model norm CSVs from the directory.
    Returns: dict { 'model_name': pd.DataFrame }
    """
    if not norms_dir.exists():
        print(f"[Loader] Directory not found: {norms_dir}")
        model_norms = {}
    else:
        model_norms = {}
        files = sorted(list(norms_dir.glob('*.csv')))
        print(f"[Loader] Found {len(files)} model norm files.")

    
    for fp in files:
        # File name is usually "model-name.csv"
        model_name = fp.stem
        
        if allowed_models:
            if not any(m in model_name for m in allowed_models):
                continue
                
        try:
            df = pd.read_csv(fp, low_memory=False)
            
            # Basic Cleaning
            # Expected columns: norm, word, cleaned_rating
            required = {'norm', 'word', 'cleaned_rating'}
            if not required.issubset(df.columns):
                print(f"[Loader] Skipping {model_name}: Missing columns {required - set(df.columns)}")
                continue
                
            df['word'] = df['word'].astype(str).str.lower().str.strip()
            df['cleaned_rating'] = pd.to_numeric(df['cleaned_rating'], errors='coerce')
            df = df.dropna(subset=['cleaned_rating'])
            
            model_norms[model_name] = df
            print(f"[Loader] Loaded norms for {model_name} ({len(df)} rows)")
            
        except Exception as e:
            print(f"[Loader] Error loading {model_name}: {e}")
            
    # --- Inject Human Norms ---
    if human_norms_path and human_norms_path.exists():
        print(f"[Loader] Loading Human Norms from {human_norms_path}...")
        try:
            df_human = pd.read_csv(human_norms_path)
            # Adapt columns: norm_name -> norm, human_rating -> cleaned_rating
            rename_map = {'norm_name': 'norm', 'human_rating': 'cleaned_rating'}
            df_human = df_human.rename(columns=rename_map)
            
            # Standardize
            if 'word' in df_human.columns and 'norm' in df_human.columns and 'cleaned_rating' in df_human.columns:
                 df_human['word'] = df_human['word'].astype(str).str.lower().str.strip()
                 df_human['cleaned_rating'] = pd.to_numeric(df_human['cleaned_rating'], errors='coerce')
                 df_human = df_human.dropna(subset=['cleaned_rating'])
                 
                 model_norms['human'] = df_human
                 print(f"[Loader] Loaded Human Norms as 'human' ({len(df_human)} rows)")
            else:
                 print(f"[Loader] Warning: Human norms file missing required columns (Need: norm_name/norm, word, human_rating/cleaned_rating)")
        except Exception as e:
             print(f"[Loader] Error loading Human Norms: {e}")

    return model_norms

def align_data(embedding_mat, cue_to_idx, norm_df, norm_name, verbose: bool = False, common_vocab: set = None):
    """
    Intersection of:
    1. Words in the embedding matrix (Rows)
    2. Words in the norm dataset (Rows for specific norm)
    3. (Optional) Common Vocabulary across all models
    
    Returns: X (features), y (targets), overlapping_words
    """
    sub_df = norm_df[norm_df['norm'] == norm_name].copy()
    
    if sub_df.empty:
        return None, None, None

    # Find overlap
    valid_cues = set(cue_to_idx.keys())
    
    # Enforce Universal Overlap if provided
    if common_vocab is not None:
        valid_cues = valid_cues.intersection(common_vocab)
        
    available_words = set(sub_df['word'].unique())
    overlap = list(valid_cues.intersection(available_words))
    
    # Logging
    norm_vocab_size = len(available_words)
    embedding_vocab_size = len(valid_cues)
    overlap_size = len(overlap)
    overlap_pct = overlap_size / norm_vocab_size if norm_vocab_size > 0 else 0
    
    dropped_emb = embedding_vocab_size - overlap_size
    dropped_norms = norm_vocab_size - overlap_size
    
    if verbose:
        print(f"    > Overlap: {overlap_size}/{norm_vocab_size} ({overlap_pct:.1%})")
        print(f"    > Drop Stats: {dropped_emb} Emb cues unused, {dropped_norms} Norm words missing.")
    
        if len(overlap) > 0:
            print(f"    > Sample Overlap: {overlap[:5]}")
            missing = list(available_words - valid_cues)
            if missing:
                print(f"    > Sample Missing (in Norms but not Emb): {missing[:5]}")
    
    if len(overlap) < MIN_SAMPLES:
        return None, None, None
        
    # Build X and y
    row_indices = [cue_to_idx[w] for w in overlap]
    X = embedding_mat[row_indices]
    
    # Handle duplicates by mean
    rating_map = sub_df.groupby('word')['cleaned_rating'].mean().to_dict()
    y = np.array([rating_map[w] for w in overlap])
    
    # STRICT FILTERING: Remove Zero Vectors
    if hasattr(X, "toarray"):
        norms = np.linalg.norm(X.toarray(), axis=1)
    else:
        norms = np.linalg.norm(X, axis=1)
        
    valid_mask = norms > 0
    if not valid_mask.all():
        dropped_zeros = np.sum(~valid_mask)
        if verbose:
            print(f"    > Dropped {dropped_zeros} rows due to Zero Vectors (Ghost Matches).")
        
        X = X[valid_mask]
        y = y[valid_mask]
        overlap = [w for i, w in enumerate(overlap) if valid_mask[i]]
        
    if len(X) < MIN_SAMPLES:
        return None, None, None
    
    # Sanity Checks
    if verbose:
        y_std = np.std(y)
        if y_std < 1e-6:
            print(f"    [Warning] Target 'y' is constant (Std={y_std:.6f}). R^2 will be 0.0 or negative.")
        
        # Check X variance
        # If sparse, convert to dense for check (careful with memory, but overlap is small ~10k)
        if hasattr(X, "toarray"):
            X_dense = X.toarray()
        else:
            X_dense = X
            
        x_std = np.std(X_dense, axis=0)
        dead_cols = np.sum(x_std < 1e-6)
        if dead_cols > 0:
            print(f"    [Warning] X has {dead_cols}/{X.shape[1]} zero-variance columns.")

    return X, y, overlap

def evaluate_embedding(X, y, random_state=42, verbose: bool = False):
    """Run Ridge Regression with Nested CV."""
    # Sanitize X
    X = np.nan_to_num(X, nan=0.0, posinf=0.0, neginf=0.0)

    model = make_pipeline(
        StandardScaler(),
        RidgeCV(alphas=DEFAULT_ALPHAS, scoring='r2')
    )
    
    cv = KFold(n_splits=CV_FOLDS, shuffle=True, random_state=random_state)
    try:
        scores = cross_val_score(model, X, y, cv=cv, scoring='r2')
        if verbose:
            model.fit(X, y)
            best_alpha = model.named_steps['ridgecv'].alpha_
            print(f"    > Best Alpha: {best_alpha}")
        return scores.mean(), scores.std()
    except Exception as e:
        if verbose:
            print(f"    [Error] Regression failed: {e}")
        return np.nan, np.nan

def process_single_norm_evaluation(emb_name, matched_model, X_full, cue_to_idx, norms_df, norm, verbose, common_vocab=None):
    """Helper to evaluate a single norm for a given embedding matrix."""
    X, y, overlap = align_data(X_full, cue_to_idx, norms_df, norm, verbose=verbose, common_vocab=common_vocab)
    
    if X is None:
        if verbose:
            print(f"    > Skipped (Insufficient Overlap)")
        return None
        
    mean_r2, std_r2 = evaluate_embedding(X, y, verbose=verbose)
    
    if np.isnan(mean_r2):
        return None
        
    return {
        'embedding_source': emb_name,
        'target_model': matched_model,
        'norm_name': norm,
        'r2_mean': mean_r2,
        'r2_std': std_r2,
        'n_samples': len(overlap)
    }

def run_evaluation_loop(embeddings_dict, mappings, model_norms_dict, output_path, verbose: bool = False, n_jobs: int = 1, cross_evaluate: bool = False, test_limit: int = 0):
    """
    Main loop.
    Logic:
    For each embedding source:
      1. Identify the model name from the key (e.g. 'passive_qwen-3-32b-instruct' -> 'qwen-3-32b-instruct')
      2. Check if we have norms for this model.
      3. If yes, evaluate on all norms present in that model's file.
    """
    results = []
    cue_to_idx = mappings['cue_to_idx']
    
    emb_keys = [k for k in embeddings_dict.keys() if k != 'mappings']
    
    print(f"[Judge] Found {len(emb_keys)} embedding sources. Processing with n_jobs={n_jobs}...")
    
    idx_to_cue = {v: k for k, v in cue_to_idx.items()}
    
    # --- UNIVERSAL STRICT OVERLAP ---
    print("[Judge] Computing Universal Strict Overlap (Common Vocabulary)...")
    common_vocab = set(cue_to_idx.keys())
    
    for k in emb_keys:
        mat = embeddings_dict[k]
        if hasattr(mat, "toarray"):
            norms = np.linalg.norm(mat.toarray(), axis=1)
        else:
            norms = np.linalg.norm(mat, axis=1)
            
        valid_indices = np.where(norms > 0)[0]
        valid_words = {idx_to_cue[idx] for idx in valid_indices}
        
        before = len(common_vocab)
        common_vocab.intersection_update(valid_words)
        after = len(common_vocab)
        if after < before:
            print(f"    > {k} reduced vocab from {before} to {after} words.")
            
    print(f"[Judge] Final Common Vocabulary Size: {len(common_vocab)}")
    
    if len(common_vocab) < MIN_SAMPLES:
        print(f"[Judge] CRITICAL: Common vocabulary is too small ({len(common_vocab)}). Aborting.")
        return

    
    # --- CHECK EXISTING RESULTS ---
    existing_df = pd.DataFrame()
    completed_keys = set()
    
    if output_path.exists():
        try:
            existing_df = pd.read_csv(output_path)
            # Ensure columns exist
            req_cols = ['embedding_source', 'target_model', 'norm_name']
            if all(c in existing_df.columns for c in req_cols):
                print(f"[Judge] Found existing results at {output_path} ({len(existing_df)} rows).")
                for _, row in existing_df.iterrows():
                    completed_keys.add((row['embedding_source'], row['target_model'], row['norm_name']))
                print(f"[Judge] Skipping {len(completed_keys)} already computed pairs.")
            else:
                print(f"[Judge] Existing file {output_path} has wrong format. Overwriting/Appending safely.")
        except Exception as e:
            print(f"[Judge] Error reading existing results: {e}. Starting fresh.")
    
    # Progress bar logic
    # Calculate total steps by summing the number of norms for each matched model
    total_steps = 0
    # Store work items to avoid re-looping complex logic
    work_items = []
    
    for emb_name in emb_keys:
        # Determine Target Models
        # Logic:
        # 1. Identify "Self" model (strict matching)
        # 2. Identify "Cross" models (if cross_evaluate=True)
        # 3. Filter "Cross" models based on embedding type (300d/Activation only)
        # 4. ALWAYS include "Self" model (Self-Consistency) regardless of type
        
        target_models = set()
        
        # 1. Self Match
        self_model = None
        for model_key in model_norms_dict.keys():
            if model_key in emb_name:
                self_model = model_key
                break
        
        if self_model:
            target_models.add(self_model)
            
        # 2. Cross Match
        if cross_evaluate:
            # Only add Cross entries if the embedding is valid for Specificity (300d or Activation)
            is_valid_for_specificity = emb_name.endswith('_300d') or emb_name.startswith('activation_')
            
            if is_valid_for_specificity:
                for m in model_norms_dict.keys():
                    target_models.add(m)
        
        if not target_models:
            if verbose:
                # print(f"[Judge] Skipping {emb_name}: No matching norms found.")
                pass
            continue
            
        for matched_model in target_models:
            norms_df = model_norms_dict[matched_model]
            all_norms = sorted(norms_df['norm'].unique())
            
            if test_limit and test_limit > 0:
                all_norms = all_norms[:test_limit]
                
            # Filter Skip Keys
            norms_to_run = []
            for norm in all_norms:
                if (emb_name, matched_model, norm) not in completed_keys:
                    norms_to_run.append(norm)
            
            if norms_to_run:
                work_items.append({
                    'emb_name': emb_name,
                    'matched_model': matched_model,
                    'norms': norms_to_run,
                    'X_full': embeddings_dict[emb_name],
                    'norms_df': norms_df
                })
                total_steps += len(norms_to_run)
            
    if total_steps == 0:
        print("[Judge] All tasks already completed. Nothing to run.")
        return

    pbar = tqdm(total=total_steps, desc="Evaluating")
    
    for item in work_items:
        emb_name = item['emb_name']
        matched_model = item['matched_model']
        norms = item['norms']
        X_full = item['X_full']
        norms_df = item['norms_df']
        
        if verbose:
             print(f"\n[Judge] Evaluating {emb_name} -> {matched_model} norms ({len(norms)} norms)...")

        # Parallelize norms for this embedding-model pair
        results_for_pair = Parallel(n_jobs=n_jobs)(
            delayed(process_single_norm_evaluation)(
                emb_name, matched_model, X_full, cue_to_idx, norms_df, norm, verbose, common_vocab
            )
            for norm in norms
        )
        
        for res in results_for_pair:
            if res:
                results.append(res)
            pbar.update(1)    
            
    # Save (Merge)
    new_res_df = pd.DataFrame(results)
    
    if not new_res_df.empty:
        if not existing_df.empty:
            final_df = pd.concat([existing_df, new_res_df], ignore_index=True)
            print(f"[Judge] Merged {len(new_res_df)} new results with {len(existing_df)} existing results.")
        else:
            final_df = new_res_df
            
        # Deduplicate just in case
        final_df = final_df.drop_duplicates(subset=['embedding_source', 'target_model', 'norm_name'])
        
        final_df.to_csv(output_path, index=False)
        print(f"\n[Judge] Self-Consistency Evaluation complete. Results saved to {output_path}")
        
        print("\n--- Leaderboard (Average R^2 across all norms) ---")
        summary = final_df.groupby('embedding_source')['r2_mean'].mean().sort_values(ascending=False)
        print(summary)
    else:
        print("\n[Judge] No new valid results produced.")


def main():
    parser = argparse.ArgumentParser(description="Evaluate Self-Consistency (Model Embeddings vs Model Norms).")
    parser.add_argument('--embeddings_path', type=Path, default=Path("outputs/matrices/embeddings.pkl"), help="Pickle from vectorize.py")
    parser.add_argument('--norms_dir', type=Path, default=Path("outputs/raw_behavior/model_norms"), help="Dir containing model norm CSVs")
    parser.add_argument('--output_dir', type=Path, default=Path("outputs/results"), help="Where to save results.csv")
    parser.add_argument('--human_norms_path', type=Path, default=Path("data/psych_norms/psychnorms_subset_filtered_by_swow.csv"), help="Path to human norms CSV (optional)")
    parser.add_argument('--models', nargs='*', help="List of model names to evaluate (substring match)")
    parser.add_argument('--verbose', action='store_true', help="Enable verbose logging")
    parser.add_argument('--n_jobs', type=int, default=-2, help="Number of parallel jobs (default -2)")
    parser.add_argument('--cross_evaluate', action='store_true', help="Evaluates EVERY embedding against EVERY model norm (Specificity)")
    parser.add_argument('--test_limit', type=int, default=0, help="Test Mode: Limit norms per model")
    args = parser.parse_args()
    
    args.output_dir.mkdir(parents=True, exist_ok=True)
    
    # Load Data
    embeddings, mappings = load_embeddings(args.embeddings_path)
    model_norms = load_model_norms(args.norms_dir, human_norms_path=args.human_norms_path, allowed_models=args.models)
    
    if not model_norms:
        print("[Judge] No model norms loaded. Exiting.")
        return

    # Run Eval
    output_csv = args.output_dir / "self_consistency_results.csv"
    run_evaluation_loop(embeddings, mappings, model_norms, output_csv, verbose=args.verbose, n_jobs=args.n_jobs, cross_evaluate=args.cross_evaluate, test_limit=args.test_limit)

